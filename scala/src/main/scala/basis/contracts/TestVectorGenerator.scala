package basis.contracts

import basis.offchain.SigUtils
import com.google.common.primitives.Longs
import scorex.crypto.encode.Base16
import scorex.crypto.hash.Blake2b256
import sigma.serialization.{GroupElementSerializer, ValueSerializer}
import sigma.ast.GroupElementConstant
import work.lithos.plasma.PlasmaParameters
import work.lithos.plasma.collections.PlasmaMap
import sigma.data.AvlTreeFlags

/**
 * Generates test vectors for cross-validation with the Rust Basis tracker implementation.
 *
 * Run with:
 *   sbt "runMain basis.contracts.TestVectorGenerator"
 *
 * The output can be copied into the Rust test files (crates/basis_store/src/schnorr_test_vectors.rs
 * and crates/basis_store/src/scala_test_vectors.rs) when regenerating reference vectors.
 */
object TestVectorGenerator extends App {

  import SigUtils._

  val g = BasisConstants.g

  val alicePubKey = ParticipantKeys.alicePublicKey
  val bobPubKey = ParticipantKeys.bobPublicKey
  val trackerPubKey = ParticipantKeys.trackerPublicKey
  val aliceSecret = ParticipantKeys.aliceSecret
  val trackerSecret = ParticipantKeys.trackerSecret

  val alicePubKeyHex = Base16.encode(alicePubKey.getEncoded.toArray)
  val bobPubKeyHex = Base16.encode(bobPubKey.getEncoded.toArray)
  val trackerPubKeyHex = Base16.encode(trackerPubKey.getEncoded.toArray)

  // Message: key || totalDebt (8 bytes BE) || timestamp (8 bytes BE) || trackerNftId (32 bytes),
  // matching contract/basis.es which appends SELF.R6[Coll[Byte]] to the signed message.
  def buildMessage(ownerKey: sigma.GroupElement, receiverKey: sigma.GroupElement, totalDebt: Long, timestamp: Long): Array[Byte] = {
    val key = Blake2b256(ownerKey.getEncoded.toArray ++ receiverKey.getEncoded.toArray)
    key ++ Longs.toByteArray(totalDebt) ++ Longs.toByteArray(timestamp) ++ BasisConstants.testTrackerNftId
  }

  // Token-denominated message: debtKey = blake2b256(owner ‖ receiver ‖ tokenId),
  // matching contract/basis-token.es (specs/ergo/multi_collateral_reserves.md).
  def buildTokenMessage(ownerKey: sigma.GroupElement, receiverKey: sigma.GroupElement, tokenId: Array[Byte], totalDebt: Long, timestamp: Long): Array[Byte] = {
    val key = Blake2b256(ownerKey.getEncoded.toArray ++ receiverKey.getEncoded.toArray ++ tokenId)
    key ++ Longs.toByteArray(totalDebt) ++ Longs.toByteArray(timestamp) ++ BasisConstants.testTrackerNftId
  }

  def vectorHeader(): Unit = {
    println("// Generated by basis.contracts.TestVectorGenerator")
    println("// Alice pubkey: " + alicePubKeyHex)
    println("// Bob pubkey:   " + bobPubKeyHex)
    println("// Tracker pubkey: " + trackerPubKeyHex)
    println("// Test tracker NFT id: " + Base16.encode(BasisConstants.testTrackerNftId))
    println()
  }

  /**
   * One-shot Schnorr sign WITHOUT the on-chain contract-safety retry in `SigUtils.sign`.
   * Returns the signature plus the Fiat-Shamir challenge bytes so callers can inspect them.
   */
  def signRaw(msg: Array[Byte], secret: BigInt): (sigma.GroupElement, BigInt, Array[Byte]) = {
    val pk = g.exp(secret.bigInteger)
    val r = randBigInt
    val a = g.exp(r.bigInteger)
    val e = Blake2b256(a.getEncoded.toArray ++ msg ++ pk.getEncoded.toArray)
    val z = (r + secret * BigInt(e)) % sigma.crypto.SecP256K1Group.q
    (a, z, e)
  }

  /**
   * Sign like `SigUtils.sign` but keep regenerating nonces until the Fiat-Shamir challenge's TOP
   * BIT IS SET, i.e. the signature is exactly the kind the reserve contract cannot evaluate
   * (`byteArrayToBigInt` reads the challenge as negative, `pubKey.exp(negative)` throws).
   */
  def signWithIncompatibleChallenge(msg: Array[Byte], secret: BigInt): (sigma.GroupElement, BigInt) = {
    val (a, z, e) = signRaw(msg, secret)
    if (!isContractCompatible(e)) (a, z) else signWithIncompatibleChallenge(msg, secret)
  }

  def sigBytes(a: sigma.GroupElement, z: BigInt): Array[Byte] =
    a.getEncoded.toArray ++ z.toByteArray.padTo(32, 0.toByte)

  def formatSchnorrVector(
    id: String,
    desc: String,
    issuer: sigma.GroupElement,
    recipient: sigma.GroupElement,
    amount: Long,
    timestamp: Long,
    msg: Array[Byte],
    sig: Array[Byte],
    shouldVerify: Boolean
  ): String = {
    val issuerHex = Base16.encode(issuer.getEncoded.toArray)
    val recipientHex = Base16.encode(recipient.getEncoded.toArray)
    val amountStr = if (amount < 0) "18446744073709551615u64" else amount + "u64"
    val timestampStr = if (timestamp < 0) "18446744073709551615u64" else timestamp + "u64"

    "  SchnorrTestVector {\n" +
    "    id: \"" + id + "\",\n" +
    "    description: \"" + desc + "\",\n" +
    "    issuer_pubkey_hex: \"" + issuerHex + "\",\n" +
    "    recipient_pubkey_hex: \"" + recipientHex + "\",\n" +
    "    amount: " + amountStr + ",\n" +
    "    timestamp: " + timestampStr + ",\n" +
    "    message_hex: \"" + Base16.encode(msg) + "\",\n" +
    "    signature_hex: \"" + Base16.encode(sig) + "\",\n" +
    "    should_verify: " + shouldVerify + ",\n" +
    "  },"
  }

  def printSchnorrVectors(): Unit = {
    println("// Schnorr signature test vectors")
    println("//")
    println("// Generated by basis.contracts.TestVectorGenerator with the bitLength <= 255 constraint,")
    println("// matching the reference implementation in scala/src/main/scala/basis/offchain/SigUtils.scala.")
    println("// Every signature with `should_verify = true` satisfies BOTH rules the reserve contract")
    println("// needs when it reads the values with the signed `byteArrayToBigInt`:")
    println("//")
    println("// * `z.bitLength <= 255`")
    println("// * the Fiat-Shamir challenge's top bit is clear")
    println("//")
    println("// SECURITY: TV003 and TV009 are generated with a nonce loop that forces the Fiat-Shamir")
    println("// challenge's top bit to be SET, so `byteArrayToBigInt` reads them as NEGATIVE and the")
    println("// contract's `pubKey.exp(e)` throws. The signatures are mathematically valid but unusable")
    println("// on-chain. They are kept with `should_verify = false` as regression coverage for exactly")
    println("// that gap: the Scala signer only checked `z` and the Rust verifier used to accept them, so")
    println("// a note carrying one could be accepted and pinned by the tracker yet never redeemed on-chain.")
    println("// See specs/pr14_triage.md (S5).")
    println("pub const SCHNORR_TEST_VECTORS: &[SchnorrTestVector] = &[")

    val amount = 1000000000L
    val timestamp = 1743379200000L
    val msgAliceToBob = buildMessage(alicePubKey, bobPubKey, amount, timestamp)

    // TV001 - standard valid signature
    {
      val (a, z) = SigUtils.sign(msgAliceToBob, aliceSecret)
      println(formatSchnorrVector("TV001", "Standard valid signature", alicePubKey, bobPubKey,
        amount, timestamp, msgAliceToBob, sigBytes(a, z), true))
    }

    // TV002 - all-zero signature
    println(formatSchnorrVector("TV002", "All-zero signature should fail", alicePubKey, bobPubKey,
      amount, timestamp, msgAliceToBob, Array.fill(65)(0.toByte), false))

    // TV003 - valid tracker signature whose challenge has the top bit set (unredeemable on-chain)
    {
      val msg = buildMessage(trackerPubKey, bobPubKey, 500000000L, 1743379201000L)
      val (a, z) = signWithIncompatibleChallenge(msg, trackerSecret)
      println(formatSchnorrVector("TV003", "SIGNATURE_WITH_INCOMPATIBLE_CHALLENGE", trackerPubKey, bobPubKey,
        500000000L, 1743379201000L, msg, sigBytes(a, z), false))
    }

    // TV004 - bob signs alice's message (wrong signer)
    {
      val (a, z) = SigUtils.sign(msgAliceToBob, ParticipantKeys.bobSecret)
      println(formatSchnorrVector("TV004", "Wrong signer signature should fail", alicePubKey, bobPubKey,
        amount, timestamp, msgAliceToBob, sigBytes(a, z), false))
    }

    // TV005 - valid signature with the last byte of z corrupted
    {
      val (a, z) = SigUtils.sign(msgAliceToBob, aliceSecret)
      val corrupted = sigBytes(a, z)
      corrupted(64) = (corrupted(64) ^ 1).toByte
      println(formatSchnorrVector("TV005", "Corrupted signature should fail", alicePubKey, bobPubKey,
        amount, timestamp, msgAliceToBob, corrupted, false))
    }

    // TV006 - signature over message with amount+1
    {
      val msg = buildMessage(alicePubKey, bobPubKey, amount + 1, timestamp)
      val (a, z) = SigUtils.sign(msg, aliceSecret)
      println(formatSchnorrVector("TV006", "Wrong amount should fail", alicePubKey, bobPubKey,
        amount, timestamp, msg, sigBytes(a, z), false))
    }

    // TV007 - signature over message with timestamp+1
    {
      val msg = buildMessage(alicePubKey, bobPubKey, amount, timestamp + 1)
      val (a, z) = SigUtils.sign(msg, aliceSecret)
      println(formatSchnorrVector("TV007", "Wrong timestamp should fail", alicePubKey, bobPubKey,
        amount, timestamp, msg, sigBytes(a, z), false))
    }

    // TV008 - message built with a different recipient key than the listed recipient_pubkey
    {
      val msg = buildMessage(alicePubKey, trackerPubKey, amount, timestamp)
      val (a, z) = SigUtils.sign(msg, aliceSecret)
      println(formatSchnorrVector("TV008", "Wrong recipient should fail", alicePubKey, bobPubKey,
        amount, timestamp, msg, sigBytes(a, z), false))
    }

    // TV009 - max u64 message with a top-bit-set challenge (unredeemable on-chain)
    {
      val msg = buildMessage(alicePubKey, bobPubKey, -1L, -1L)
      val (a, z) = signWithIncompatibleChallenge(msg, aliceSecret)
      println(formatSchnorrVector("TV009", "SIGNATURE_WITH_INCOMPATIBLE_CHALLENGE (max u64 message)",
        alicePubKey, bobPubKey, -1L, -1L, msg, sigBytes(a, z), false))
    }

    // TV010 - zero amount and timestamp
    {
      val msg = buildMessage(alicePubKey, bobPubKey, 0L, 0L)
      val (a, z) = SigUtils.sign(msg, aliceSecret)
      println(formatSchnorrVector("TV010", "Zero amount and timestamp", alicePubKey, bobPubKey,
        0L, 0L, msg, sigBytes(a, z), true))
    }

    // TV011 - emergency redemption valid reserve signature
    {
      val msg = buildMessage(alicePubKey, bobPubKey, 500000000L, 1743379202000L)
      val (a, z) = SigUtils.sign(msg, aliceSecret)
      println(formatSchnorrVector("TV011", "Emergency redemption valid reserve signature", alicePubKey, bobPubKey,
        500000000L, 1743379202000L, msg, sigBytes(a, z), true))
    }

    // TV012 - token-denominated note (namespaced debtKey) valid signature
    {
      val tokenId = Base16.decode("a55b8735ed1a99e46c2c89f8994aacdf4b1109bdcf682f1e5b34479c6e392669").get
      val msgToken = buildTokenMessage(alicePubKey, bobPubKey, tokenId, amount, timestamp)
      val (a, z) = SigUtils.sign(msgToken, aliceSecret)
      println(formatSchnorrVector("TV012", "Token-denominated note (namespaced debtKey)", alicePubKey, bobPubKey,
        amount, timestamp, msgToken, sigBytes(a, z), true))
    }
    println("// Token id for TV012: a55b8735ed1a99e46c2c89f8994aacdf4b1109bdcf682f1e5b34479c6e392669")
    println("];")
    println()
  }

  def printSerializedConstants(): Unit = {
    println("// Serialized Ergo constants")
    println("pub const ACTION_BYTE_SERIALIZED: &str = \"" + Base16.encode(ValueSerializer.serialize(0.toByte)) + "\";")
    println("pub const TOTAL_DEBT_SERIALIZED: &str = \"" + Base16.encode(ValueSerializer.serialize(50000000L)) + "\";")
    println("pub const TIMESTAMP_SERIALIZED: &str = \"" + Base16.encode(ValueSerializer.serialize(1743379200000L)) + "\";")
    println("pub const ALICE_PUBKEY_SERIALIZED: &str = \"" + Base16.encode(ValueSerializer.serialize(GroupElementConstant(alicePubKey))) + "\";")
    println("pub const BOB_PUBKEY_SERIALIZED: &str = \"" + Base16.encode(ValueSerializer.serialize(GroupElementConstant(bobPubKey))) + "\";")
    println()
  }

  def printAvlVectors(): Unit = {
    println("// AVL tree test vectors")

    val params = PlasmaParameters(32, None)
    val trackerMap = new PlasmaMap[Array[Byte], Array[Byte]](AvlTreeFlags.InsertOnly, params)
    val reserveMap = new PlasmaMap[Array[Byte], Array[Byte]](AvlTreeFlags(insertAllowed = true, updateAllowed = true, removeAllowed = false), params)

    val key1 = Blake2b256(alicePubKey.getEncoded.toArray ++ bobPubKey.getEncoded.toArray)
    val totalDebt1 = Longs.toByteArray(50000000L)
    trackerMap.insert((key1, totalDebt1))
    val trackerTree = trackerMap.ergoValue.getValue
    val trackerProof = trackerMap.lookUp(key1).proof.bytes

    println("pub const TRACKER_AVL_VECTORS: &[AvlTestVector] = &[")
    println("  AvlTestVector {")
    println("    id: \"AVL_T001\",")
    println("    description: \"Tracker tree with single debt entry (50M nanoERG)\",")
    println("    key_hex: \"" + Base16.encode(key1) + "\",")
    println("    value_hex: \"" + Base16.encode(totalDebt1) + "\",")
    println("    proof_hex: \"" + Base16.encode(trackerProof) + "\",")
    println("    root_digest_hex: \"" + Base16.encode(trackerTree.digest.toArray) + "\",")
    println("    tree_type: \"tracker\",")
    println("  },")
    println("];")
    println()

    val timestamp = 1743379200000L
    val redeemed = 25000000L
    val reserveValue = Longs.toByteArray(timestamp) ++ Longs.toByteArray(redeemed)
    reserveMap.insert((key1, reserveValue))
    val reserveTree = reserveMap.ergoValue.getValue
    val reserveProof = reserveMap.lookUp(key1).proof.bytes

    println("pub const RESERVE_AVL_VECTORS: &[AvlTestVector] = &[")
    println("  AvlTestVector {")
    println("    id: \"AVL_R001\",")
    println("    description: \"Reserve tree with first redemption (timestamp=" + timestamp + ", redeemed=" + redeemed + ")\",")
    println("    key_hex: \"" + Base16.encode(key1) + "\",")
    println("    value_hex: \"" + Base16.encode(reserveValue) + "\",")
    println("    proof_hex: \"" + Base16.encode(reserveProof) + "\",")
    println("    root_digest_hex: \"" + Base16.encode(reserveTree.digest.toArray) + "\",")
    println("    tree_type: \"reserve\",")
    println("  },")
    println("];")
    println()
  }

  vectorHeader()
  printSchnorrVectors()
  printSerializedConstants()
  printAvlVectors()
}
